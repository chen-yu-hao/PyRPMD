"""OpenMolcas RASSCF/CASPT2 file interface (parser tested; executable untested)."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Sequence

import numpy as np

from .base import BackendFailure, ExcitedStateStatus
from .external import FileProgramBackend, ParsedExternalResult, parse_gradient_blocks, parse_transition_properties


class OpenMolcasExcitedStateBackend(FileProgramBackend):
    name = "openmolcas"
    input_filename = "job.inp"
    output_filename = "job.out"
    wavefunction_filenames = ("job.RasOrb", "job.JobIph", "job.JobMix")
    sidecar_filenames = ("geometry.xyz",)

    DEFAULT_TEMPLATE = """&GATEWAY
Coord=$CurrDir/geometry.xyz
Basis={basis}
Group=Nosym

&SEWARD

&SCF
Charge={charge}
Spin={spin}

&RASSCF
NROFJOBIPH={nstates}
CIROOT={nstates} {nstates} 1
{method_block}

&ALASKA
"""

    def __init__(
        self,
        symbols: Sequence[str],
        nstates: int,
        *,
        program_version: str,
        method: str = "RASSCF",
        basis: str = "ANO-S-VDZP",
        charge: int = 0,
        multiplicity: int = 1,
        command: Sequence[str] = ("pymolcas", "{input}"),
        input_template: str = DEFAULT_TEMPLATE,
        **kwargs,
    ):
        if method.upper() != "RASSCF" and input_template == self.DEFAULT_TEMPLATE:
            raise ValueError(
                "post-RASSCF OpenMolcas methods require an explicit input_template; "
                "the default template contains RASSCF only"
            )
        super().__init__(
            symbols,
            nstates,
            program_version=program_version,
            method=method,
            basis=basis,
            charge=charge,
            multiplicity=multiplicity,
            command=command,
            input_template=input_template,
            **kwargs,
        )

    def prepare_files(self, geometry: np.ndarray, scratch: Path) -> None:
        xyz = [str(len(self.symbols)), "bohr; generated by PyRPMD"]
        xyz.extend(
            f"{symbol:2s} {x: .16f} {y: .16f} {z: .16f}"
            for symbol, (x, y, z) in zip(self.symbols, geometry)
        )
        (scratch / "geometry.xyz").write_text("\n".join(xyz) + "\n", encoding="utf-8")

    def render_input(self, geometry: np.ndarray) -> str:
        method_block = "" if self.method.upper() == "RASSCF" else f"! custom method: {self.method}"
        return self.input_template.format(
            method=self.method,
            basis=self.basis,
            charge=self.charge,
            spin=self.multiplicity - 1,
            nstates=self.nstates,
            method_block=method_block,
        )

    def parse_output(self, text: str) -> ParsedExternalResult:
        lower = text.lower()
        if "scf did not converge" in lower or "no convergence after" in lower:
            raise BackendFailure(ExcitedStateStatus.SCF_NOT_CONVERGED, "OpenMolcas SCF did not converge")
        if "happy landing" not in lower:
            raise BackendFailure(ExcitedStateStatus.EXTERNAL_PROGRAM_FAILED, "OpenMolcas output lacks Happy landing")
        energies = {}
        for root, value in re.findall(
            r"RASSCF root number\s+(\d+)\s+Total energy:\s*([-+0-9.DEde]+)", text
        ):
            energies[int(root) - 1] = float(value.replace("D", "E"))
        required = set(range(self.nstates))
        missing = sorted(required.difference(energies))
        if missing:
            raise BackendFailure(
                ExcitedStateStatus.STATE_COUNT_MISMATCH,
                "OpenMolcas is missing roots " + ", ".join(str(state + 1) for state in missing),
            )
        values = np.array([energies[state] for state in range(self.nstates)])
        gradients = parse_gradient_blocks(text, nstates=self.nstates, natoms=len(self.symbols))
        strengths, dipoles = parse_transition_properties(text, nstates=self.nstates)
        return ParsedExternalResult(values, gradients, strengths, dipoles, {"parser": "openmolcas-v1"})
