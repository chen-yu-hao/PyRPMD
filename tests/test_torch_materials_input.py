def job(task="pimd", engine="torch"):
    data = {"task": task, "temperature": "300 K", "beads": 4, "seed": 17,
        "system": {"symbols": ["H", "He"], "masses": [2., 5.],
                   "geometry": [[.1, -.2, .3], [.4, .5, -.1]], "geometry_unit": "bohr"},
        "potential": ({"provider": "harmonic", "params": {"k": .2}}
                      if task == "pimd" else {"provider": "free"}),
        "dynamics": {"timestep": .04, "integrator": "cayley-bcb"},
        "sampling": {"thermostat": "pile-l", "integrator": "bcocb", "gamma_centroid": .7,
                     "equilibration_steps": 3, "production_steps": 24,
                     "sample_interval": 2, "replicas": 2},
        "output": {"checkpoint_steps": 4, "chunk_frames": 3}}
    if engine is not None:
        data["sampling"]["engine"] = engine
    if engine == "torch":
        data["sampling"].update(device="cpu", normal_mode_layout="rfft")
    if task == "diffusion":
        data["diffusion"] = {"atom_indices": [0], "axes": [0, 1, 2], "bootstrap": 0, "max_lag": 3}
    return data


def source_job(path, data):
    path.write_text("def build():\n    return " + repr(data) + "\n", encoding="utf-8")
    return path


def scientific_id(data):
    config, system = JobSpec.from_mapping(data).resolve()
    return fingerprint(scientific_config(config), system)


@pytest.mark.parametrize("task", ["pimd", "diffusion"])
def test_public_resolution_defaults_are_explicit_for_torch_only(task):
    raw = job(task)
    raw["sampling"].pop("device")
    raw["sampling"].pop("normal_mode_layout")
    raw["sampling"].pop("integrator")
    raw["dynamics"]["integrator"] = "normal-mode-bab"
    before = copy.deepcopy(raw)
    config, system = JobSpec.from_mapping(raw).resolve()
    assert raw == before
    assert config["sampling"]["engine"] == "torch"
    assert config["sampling"]["device"] == "cpu"
    assert config["sampling"]["normal_mode_layout"] == "rfft"
    assert config["sampling"]["integrator"] == "bcocb"
    assert config["dynamics"]["integrator"] == "normal-mode-bab"
    assert config["sampling"]["gamma_centroid"] == .7
    assert system.natoms == 2


