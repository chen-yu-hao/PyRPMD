@pytest.mark.parametrize("task", ["pimd", "diffusion"])
def test_cli_validate_run_resume_analyze(tmp_path, capsys, task):
    source = source_job(tmp_path / "job.py", job(task))
    output = tmp_path / "run"
    assert main(["validate", str(source), "--check-pes"]) == 0
    checked = json.loads(capsys.readouterr().out)
    assert checked["pes_check"]["frames"] == 8
    assert main(["run", str(source), "--output", str(output)]) == 0
    first = json.loads(capsys.readouterr().out)
    assert first["engine"] == "torch" and first["status"] == "complete"
    assert first["converged"] is False and first["physical_converged"] is False
    checkpoint = Path(first["batch_checkpoint"])
    before = checkpoint.read_bytes()
    assert main(["resume", str(output), "--block-steps", "3"]) == 0
    resumed = json.loads(capsys.readouterr().out)
    assert resumed["samples_per_replica"] == first["samples_per_replica"]
    assert checkpoint.read_bytes() == before
    arguments = ["analyze", str(output)]
    if task == "diffusion":
        arguments += ["--recompute", "--bootstrap", "0", "--axes", "0", "--max-lag", "3"]
    assert main(arguments) == 0
    analyzed = json.loads(capsys.readouterr().out)
    assert analyzed["engine"] == "torch"
    assert checkpoint.read_bytes() == before
    if task == "diffusion":
        assert analyzed["diffusion"]["input"]["axes"] == [0]
        assert analyzed["diffusion_m2_s"] is None  # Free particles are ballistic.


