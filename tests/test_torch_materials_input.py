def test_public_interrupted_resume_accepts_block_and_chunk_changes(tmp_path, monkeypatch):
    raw = job("diffusion")
    reference = run(raw, output=tmp_path / "reference")
    original = TorchDynamics.propagate
    def fail(self, state, steps):
        result = original(self, state, steps)
        if state.step >= 5:
            raise RuntimeError("public interruption")
        return result
    with monkeypatch.context() as patch:
        patch.setattr(TorchDynamics, "propagate", fail)
        with pytest.raises(RuntimeError, match="public interruption"):
            run(raw, output=tmp_path / "resumed")
    changed = copy.deepcopy(raw)
    changed["dynamics"]["block_steps"] = 3
    changed["output"].update(chunk_frames=5, checkpoint_steps=7)
    assert scientific_id(changed) == scientific_id(raw)
    actual = run(changed, output=tmp_path / "resumed", resume=True)
    with load_checkpoint(reference["batch_checkpoint"]) as expected, load_checkpoint(actual["batch_checkpoint"]) as resumed:
        for name in ("q", "p", "step", "time", "rng_sampling", "rng_production"):
            np.testing.assert_array_equal(resumed[name], expected[name])
    assert actual["diffusion"] == reference["diffusion"]


def test_changed_real_model_source_is_rejected_on_resume_and_reanalysis(tmp_path):
    source = tmp_path / "tensor_model.py"
    source.write_text(
        "import torch\n"
        "class Model(torch.nn.Module):\n"
        "    metadata = {'batch_independent': True}\n"
        "    def forward(self, q):\n"
        "        return q.square().sum((1, 2)) / 2, -q\n"
        "def make(device='cpu'):\n"
        "    return Model().to(device=device, dtype=torch.float64)\n", encoding="utf-8")
    raw = job("diffusion")
    raw["potential"] = {"provider": "torch", "factory": str(source) + ":make", "device": "cpu"}
    config, _ = JobSpec.from_mapping(raw).resolve()
    assert str(source) in referenced_files(config)
    output = tmp_path / "run"
    first = run(raw, output=output)
    before = Path(first["batch_checkpoint"]).read_bytes()
    source.write_text(source.read_text(encoding="utf-8") + "\n# changed source\n", encoding="utf-8")
    with pytest.raises(RuntimeError, match="changed|source"):
        resume_run(output)
    with pytest.raises(RuntimeError, match="changed|source"):
        analyze_run(output, recompute=True)
    assert Path(first["batch_checkpoint"]).read_bytes() == before


def test_unavailable_cuda_is_rejected_by_numerical_prepare_without_output(tmp_path, monkeypatch):
    from pyrpmd.potentials.base import BackendUnavailableError
    raw = job()
    raw["sampling"]["device"] = "cuda"
    raw["output"]["directory"] = str(tmp_path / "not-created")
    assert prepare(raw, numerical=False)["ready"]  # Structural inspection is hardware-independent.
    empty = torch.empty
    def unavailable(*args, **kwargs):
        if str(kwargs.get("device", "")).startswith("cuda"):
            raise RuntimeError("unavailable CUDA test fixture")
        return empty(*args, **kwargs)
    monkeypatch.setattr(torch, "empty", unavailable)
    with pytest.raises(BackendUnavailableError, match="no device fallback"):
        prepare(raw, numerical=True)
    assert not (tmp_path / "not-created").exists()


