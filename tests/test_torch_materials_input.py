def test_structural_preparation_neither_imports_torch_nor_loads_provider(tmp_path, monkeypatch):
    import pyrpmd.potentials as potentials
    raw = job()
    raw["output"]["directory"] = str(tmp_path / "not-created")
    original_import = builtins.__import__
    def checked_import(name, *args, **kwargs):
        if name == "torch" or name.startswith("torch."):
            raise AssertionError("structural preparation imported Torch")
        return original_import(name, *args, **kwargs)
    def unexpected(*args, **kwargs):
        raise AssertionError("structural preparation constructed a provider")
    monkeypatch.setattr(builtins, "__import__", checked_import)
    monkeypatch.setattr(potentials, "make_potential", unexpected)
    result = prepare(raw, numerical=False)
    assert result["ready"] and "pes_check" not in result
    details = result["materials_preparation"]
    assert details["engine"] == "torch" and details["dtype"] == "float64"
    assert details["sampling_integrator"] == "bcocb"
    assert details["batch_replicas"] == 2
    assert not (tmp_path / "not-created").exists()


@pytest.mark.parametrize("task", ["pimd", "diffusion"])
def test_numerical_preparation_evaluates_complete_batch_without_propagation(tmp_path, monkeypatch, task):
    raw = job(task)
    raw["output"]["directory"] = str(tmp_path / "not-created")
    def unexpected(*args, **kwargs):
        raise AssertionError("numerical preparation propagated")
    monkeypatch.setattr(TorchDynamics, "propagate", unexpected)
    result = prepare(raw, numerical=True)
    checked = result["pes_check"]
    assert checked["engine"] == "torch" and checked["device"] == "cpu"
    assert checked["step"] == 0 and checked["frames"] == 8
    assert checked["status"] == [0] * 8
    expected = .5 * .2 * np.square(raw["system"]["geometry"]).sum() if task == "pimd" else 0.
    np.testing.assert_allclose(checked["energy_hartree"], [expected] * 8, rtol=1e-14)
    assert not (tmp_path / "not-created").exists()


def test_numerical_preparation_closes_owned_provider(tmp_path, monkeypatch):
    import pyrpmd.potentials as potentials
    from pyrpmd.potentials.builtin import FreePotential
    provider, closed = FreePotential(), []
    provider.close = lambda: closed.append(True)
    monkeypatch.setattr(potentials, "make_potential", lambda *args: provider)
    raw = job("diffusion")
    raw["output"]["directory"] = str(tmp_path / "not-created")
    prepare(raw, numerical=True)
    assert closed == [True]
    assert not (tmp_path / "not-created").exists()


