"""Re-evaluate preserved independent pilots, then run new coordinate-kinetic checks.

The optional --pilot-dir files are from PR #134's documented finite-P pilots;
this program does NOT claim they are new trajectories. The exact kinetic checks
and all new selector outputs are generated by this script. No full molecular
quantum rate is evaluated or used in selection.
"""
from pathlib import Path
import sys,json,time,argparse,hashlib
import numpy as np
from scipy.interpolate import CubicSpline
ROOT=Path(__file__).resolve().parents[2];sys.path.insert(0,str(ROOT/'src'))
from pyrpmd.analysis.goal_quantum_coordinates import screen_goal_subspace,fit_graph_chart,GraphCoordinateChart,arc_length_chart
from pyrpmd.analysis.curvilinear_quantum import cartesian_geometry,audit_chart,solve_curvilinear,triatomic_transfer_geometry
from pyrpmd.analysis.curvilinear_propagation import propagate_curvilinear


def force(q,kind):
    x=q[:,0];f=np.zeros_like(q)
    if kind=='morse':
        dep=np.array([8,6,5]);a=np.array([.5,.55,.6]);ex=np.exp(-a*q)
        return 2*dep*a*ex*(ex-1)
    if kind=='fermi':
        y=q[:,1];b=q[:,2];f[:,0]=-4*x-.35*y*y+1.69*.15*(b-.15*x)
        f[:,1]=-y-.7*x*y-4*(.35**2/8+.005)*y**3;f[:,2]=-1.69*(b-.15*x)
        return f
    t=np.tanh(x);v=np.tanh(2*x);dis=q[:,1]-.65*v
    f[:,0]=2*t*(1-t*t)+2.25*dis*1.3*(1-v*v)
    f[:,1]=-2.25*dis+.529*(q[:,2]-.1*q[:,1]);f[:,2]=-5.29*(q[:,2]-.1*q[:,1]);return f


def run(pilot_dir,out):
    out.mkdir(parents=True,exist_ok=True);summary={'scope':'coordinate selection and full-chart kinetic validation, NOT molecular rate validation','pilots':{},'metric_checks':[]}
    if pilot_dir is not None:
        for kind in ['morse','fermi','eckart']:
            file=pilot_dir/f'pilot_{kind}.npz';data=np.load(file);q=data['q'][:,::4,:].reshape(-1,3);f=force(q,kind)
            per=data['q'].shape[1]//4
            groups=np.repeat(np.arange(len(data['q'])) if kind=='fermi' else np.arange(len(data['q']))//4,per)
            a=np.array([1.,0,0]);r=screen_goal_subspace(q,f,np.ones(3),a,groups)
            record=r.as_dict();record['pilot_sha256']=hashlib.sha256(file.read_bytes()).hexdigest();record['reuses_PR134_pilot']=True
            record['source_sampling_equilibrium_converged']=False;record['target']='x position response, not total energy'
            # Rotation is applied to positions, forces, and the same target together.
            R=np.linalg.qr(np.random.default_rng(319).normal(size=(3,3)))[0]
            rr=screen_goal_subspace(q@R,f@R,np.ones(3),a@R,groups)
            p=r.basis_mass_weighted@r.basis_mass_weighted.T;pr=R@rr.basis_mass_weighted@rr.basis_mass_weighted.T@R.T
            record['rotation_projector_error']=float(np.linalg.norm(p-pr))
            if kind=='morse':record['all_coordinates_target']=screen_goal_subspace(q,f,np.ones(3),np.eye(3),groups).as_dict()
            summary['pilots'][kind]=record;print(kind,record['required_dimension'],record['status'],record['diagnostics']['holdout_relative_force_error'],flush=True)
    # Independent canonical P=1 graph-trough pilot: exact rejection in s, Gaussian bath.
    # This validates learned geometry only, not quantum selection/real-time accuracy.
    rng=np.random.default_rng(20261108);parts=[]
    while sum(len(p) for p in parts)<5000:
        s=rng.uniform(-2.8,2.8,10000);V=.25*(s*s-1.5**2)**2
        parts.append(s[rng.random(len(s))<np.exp(-4*V)])
    s=np.concatenate(parts)[:5000]
    q=np.column_stack([s,.5*s*s+rng.normal(0,.04,len(s)),.35*np.sin(s)+rng.normal(0,.05,len(s))])
    chart=fit_graph_chart(q[:3500],np.ones(3),[1,0,0],knots=8)
    good=(s[3500:]>chart.support[0]+1e-4)&(s[3500:]<chart.support[1]-1e-4)
    test=q[3500:][good];u=chart.inverse(test)
    cov=np.linalg.eigvalsh(np.cov(q.T))[::-1];ret=np.cumsum(cov)/cov.sum()
    g=audit_chart(chart,u)
    g.update({'linear_PCA_dimension_at_99percent':int(np.searchsorted(ret,.99)+1),'transverse_holdout_RMS':float(np.sqrt(np.mean(u[:,1:]**2))),
              'chart_active_progress_variables':1,'sampling':'exact canonical P=1 graph-trough sample; geometry control only','N_train':3500,'N_holdout':len(test)})
    summary['learned_graph']=g
    ac=arc_length_chart(chart);au=ac.inverse(test)
    summary['arc_length_chart']=audit_chart(ac,au,step=1e-6)
    np.savez_compressed(out/'learned_graph.npz',cartesian=test,curvilinear=u,pca_fraction=ret)
    # Full 2D harmonic Hamiltonian under nonlinear shear. Same physical oscillator;
    # analytic levels 1,2,2,3. Wrong-flat-mass calculation is a failure control.
    t=np.linspace(-6,6,40);c=GraphCoordinateChart(np.zeros(2),np.eye(2),np.ones(2),(CubicSpline(t,.6*t*t),),(-6.,6.))
    for n in [31,51,81,121]:
        start=time.perf_counter();axes=[np.linspace(-5,5,n),np.linspace(-7,7,n)]
        pot=lambda u:.5*np.sum(c.forward(u)**2,axis=1)
        result=solve_curvilinear(axes,lambda u:cartesian_geometry(c,u),pot,states=4)
        flat=solve_curvilinear(axes,lambda u:(np.broadcast_to(np.eye(2),(len(u),2,2)),np.ones(len(u))),pot,states=4)
        rec={'nodes_per_axis':n,'energies_correct_metric':result.energies.tolist(),'energies_wrong_flat_metric':flat.energies.tolist(),
             'relative_ground_error_correct':float(abs(result.energies[0]-1)),'relative_ground_error_wrong':float(abs(flat.energies[0]-1)),
             'diagnostics':result.diagnostics,'elapsed_seconds':time.perf_counter()-start}
        summary['metric_checks'].append(rec);print('metric',n,rec['energies_correct_metric'],rec['energies_wrong_flat_metric'],flush=True)
    state=(result.vectors[:,0]+1j*result.vectors[:,1])/np.sqrt(2)
    propagated=propagate_curvilinear(result,state,np.linspace(0,20,41),hbar=1.)
    summary['nonlinear_coordinate_propagation']={k:v for k,v in propagated.items() if k not in ('time','wavefunctions','mass_norm')}
    summary['nonlinear_coordinate_propagation']['norm_range']=[float(propagated['mass_norm'].min()),float(propagated['mass_norm'].max())]
    # Local molecular geometry audit (not a sampled noncollinear ensemble).
    r1,r2=2.7204565,3.6420790
    ang=np.deg2rad([120,150,170,179]);m=np.array([78.9183376,1.00782503223,34.968852682])*1822.888486209
    points=np.column_stack([np.full(4,np.log(r1/r2)),np.full(4,np.log(r1+r2)),ang])
    G,rho=triatomic_transfer_geometry(points,m)
    summary['ClHBr_coordinate_audit']={'angles_degrees':[120,150,170,179],'coordinate_labels':['log(r_BrH/r_HCl)','log(r_BrH+r_HCl)','theta'],
        'inverse_mass_eigenvalues':np.linalg.eigvalsh(G).tolist(),'density':rho.tolist(),'scope':'J=0 local geometry only; no new scattering or rate',
        'quantum_core_dimension':None,'dimension_approved':False,'finite_J_rotation_supported':False}
    (out/'summary.json').write_text(json.dumps(summary,indent=2));return summary

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--pilot-dir',type=Path);ap.add_argument('--output',type=Path,default=ROOT/'results');a=ap.parse_args();run(a.pilot_dir,a.output)
